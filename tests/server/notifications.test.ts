import { afterEach, expect, test } from "vitest";
import { createTestDb } from "../helpers/db";
import { seedUser } from "../helpers/fixtures";
const cleanup: Array<() => Promise<void>> = [];
afterEach(async () => { for (const close of cleanup.splice(0).reverse()) await close(); });
test("notifications are recipient-private; marking one/all read is idempotent and emits no domain events", async () => {
  const { db, close } = await createTestDb(); cleanup.push(close);
  const a = await seedUser(db); const b = await seedUser(db);
  const { createTaskService } = await import("@/server/tasks/service"); const tasks = createTaskService(db);
  await tasks.create(a.actor, { title: "First" }); await tasks.create(b.actor, { title: "Second" });
  const { createNotificationService } = await import("@/server/notifications/service"); const notifications = createNotificationService(db);
  const own = await notifications.list(a.actor); const foreign = await notifications.list(b.actor);
  expect(own.items).toHaveLength(2); expect(own.unreadCount).toBe(2);
  await expect(notifications.markRead(a.actor, foreign.items[0].id)).rejects.toMatchObject({ code: "NOT_FOUND" });
  await notifications.markRead(a.actor, own.items[0].id); await notifications.markRead(a.actor, own.items[0].id);
  expect(await notifications.unreadCount(a.actor)).toBe(1);
  await notifications.markAllRead(a.actor); expect(await notifications.unreadCount(a.actor)).toBe(0);
  expect(await notifications.unreadCount(b.actor)).toBe(2); expect(await db.activityEvent.count()).toBe(2);
  await db.user.delete({ where: { id: a.actor.id } });
  await expect(notifications.list(a.actor)).rejects.toMatchObject({ code: "UNAUTHENTICATED" });
});
